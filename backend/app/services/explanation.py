from typing import Dict, Optional
from app.models.schemas import ExplanationByLevel, ExecutionResult

class ExplanationService:
    @staticmethod
    def generate_explanation(
        prompt: str,
        circuit_code: str,
        result: ExecutionResult,
        backend_id: str = "aer_simulator"
    ) -> ExplanationByLevel:
        total_shots = sum(result.raw_result.values()) if result.raw_result else 1024
        outcomes_str = ", ".join(f"|{k}>: {v} shots ({(v/total_shots)*100:.1f}%)" for k, v in (result.raw_result or {}).items())
        
        is_sim = "simulator" in backend_id.lower() or "aer" in backend_id.lower()
        backend_context = "ran on an idealized local simulator" if is_sim else f"ran on physical quantum hardware ({backend_id})"
        uncertainty_note = "As an idealized simulation, there are zero environmental decoherence errors." if is_sim else "Results incorporate physical thermal relaxation (T1) and dephasing (T2) noise."

        beginner = (
            f"Your experiment '{prompt}' was executed ({backend_context}) with {total_shots} total trials. "
            f"The final observed outcomes were: {outcomes_str}. {uncertainty_note}"
        )

        intermediate = (
            f"Circuit measurement over {total_shots} shots collapsed the quantum wave function into the following distribution: {outcomes_str}. "
            f"This confirms the state superposition/entanglement generated by your quantum gates. {uncertainty_note}"
        )

        technical = (
            f"Quantum measurement sampling under {backend_id} (N={total_shots} shots) yielded empirical probability distribution: {outcomes_str}. "
            f"Statistical deviation conforms to standard quantum projection noise sigma ~ 1/sqrt(N). {uncertainty_note}"
        )

        return ExplanationByLevel(
            beginner=beginner,
            intermediate=intermediate,
            technical=technical
        )
